def request_text(stage, intent, controls, selected_style=''):
    """Values are JSON data, not concatenated instructions or system prompts."""
    import json
    if stage not in ('analyze', 'refine'):
        raise ValueError('未知 AI 编辑阶段。')
    if not isinstance(intent, str) or len(intent) > 2000:
        raise ValueError('修图要求请保持在 2000 字以内。')
    if not isinstance(selected_style, str) or len(selected_style) > 160:
        raise ValueError('所选风格无效。')
    instruction = ANALYZE_PROMPT if stage == 'analyze' else REFINE_PROMPT
    return instruction + '\n输入数据：\n' + json.dumps(dict(
        user_intent=intent.strip(), selected_style=selected_style,
        controls=controls), ensure_ascii=False, allow_nan=False, separators=(',', ':'))
